

-- Q1: raise_amount(emp_id, raise_pct)
CREATE OR REPLACE PROCEDURE raise_amount (
    p_emp_id IN employees.employee_id%TYPE,
    p_raise  IN NUMBER   -- e.g. 0.10 = 10%
)
AS
BEGIN
    UPDATE employees
    SET salary = salary + (salary * p_raise)
    WHERE employee_id = p_emp_id;

    COMMIT;
END raise_amount;
/
SHOW ERRORS;

-- Q2: DisplayEmployeeInfo(emp_id)
CREATE OR REPLACE PROCEDURE DisplayEmployeeInfo (
    EmpNum IN employees.employee_id%TYPE
)
AS
    v_name   employees.first_name%TYPE;
    v_job    employees.job_id%TYPE;
    v_salary employees.salary%TYPE;
BEGIN
    SELECT first_name, job_id, salary
    INTO v_name, v_job, v_salary
    FROM employees
    WHERE employee_id = EmpNum;

    DBMS_OUTPUT.PUT_LINE('Employee Name: ' || v_name);
    DBMS_OUTPUT.PUT_LINE('Employee Position: ' || v_job);
    DBMS_OUTPUT.PUT_LINE('Salary: ' || v_salary);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('No employee found for EmpNum = ' || EmpNum);
END DisplayEmployeeInfo;
/
SHOW ERRORS;

-- Q3: insert_department (upsert: exists->update, not exists->insert)
CREATE OR REPLACE PROCEDURE insert_department (
    p_dept_no   IN NUMBER,
    p_dept_name IN VARCHAR2
)
IS
BEGIN
    MERGE INTO departments d
    USING (SELECT p_dept_no AS dept_id, p_dept_name AS dept_name FROM dual) s
    ON (d.department_id = s.dept_id)
    WHEN MATCHED THEN
        UPDATE SET d.department_name = s.dept_name
    WHEN NOT MATCHED THEN
        INSERT (department_id, department_name)
        VALUES (s.dept_id, s.dept_name);

    COMMIT;
END insert_department;
/
SHOW ERRORS;

