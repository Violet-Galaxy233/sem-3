-- Trigger Exercise 1: PURCHASE table + trigger
CREATE TABLE purchase (
    product  VARCHAR2(16),
    quantity NUMBER,
    price    NUMBER(8,2),
    cost     NUMBER
);

CREATE OR REPLACE TRIGGER purchase_trig
BEFORE INSERT OR UPDATE ON purchase
FOR EACH ROW
BEGIN
    :NEW.cost := :NEW.quantity * :NEW.price;
END purchase_trig;
/
SHOW ERRORS;

-- Trigger Exercise 2: EMP_COPY + EMP_AUDIT + trigger
CREATE TABLE emp_copy AS
SELECT * FROM employees;

CREATE TABLE emp_audit (
    audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id      NUMBER NOT NULL,
    old_salary  NUMBER NOT NULL,
    new_salary  NUMBER NOT NULL,
    change_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    changed_by  VARCHAR2(50)
);

CREATE OR REPLACE TRIGGER trg_salary_increase
AFTER UPDATE OF salary ON emp_copy
FOR EACH ROW
WHEN (NEW.salary > OLD.salary)
BEGIN
    INSERT INTO emp_audit (
        emp_id,
        old_salary,
        new_salary,
        change_date,
        changed_by
    )
    VALUES (
        :OLD.employee_id,
        :OLD.salary,
        :NEW.salary,
        SYSTIMESTAMP,
        USER
    );
END;
/
SHOW ERRORS;

